#!/usr/bin/env python3
"""Generates assets.h from the files in data/ (kbSensors.css/js/svg).

The firmware serves them from LittleFS when they are there and falls back to these
embedded copies otherwise, so the web UI also works on a device where the data/ folder
was never uploaded (or the filesystem was reformatted). Run it after editing data/*:

    python3 embed_assets.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
files = [
    ("kbSensors.css", "text/css"),
    ("kbSensors.js", "application/javascript"),
    ("kbSensors.svg", "image/svg+xml"),
]

out = ["// Generated by embed_assets.py from data/ - do not edit by hand.", "#pragma once", ""]
table = []
for i, (name, ctype) in enumerate(files):
    with open(os.path.join(here, "data", name), "rb") as f:
        raw = f.read().replace(b"\r\n", b"\n")
    out.append("static const char ASSET_%d[] PROGMEM = {" % i)
    for j in range(0, len(raw), 16):
        out.append("  " + ", ".join("0x%02x" % b for b in raw[j:j + 16]) + ",")
    out.append("};")
    out.append("")
    table.append('    {"%s", "%s", ASSET_%d, %d},' % (name, ctype, i, len(raw)))

out.append("struct EmbeddedAsset {")
out.append("  const char *name;")
out.append("  const char *contentType; // in RAM (short)")
out.append("  const char *data;        // PROGMEM")
out.append("  size_t size;")
out.append("};")
out.append("")
out.append("static const EmbeddedAsset embeddedAssets[] = {")
out.extend(table)
out.append("};")
out.append("")

with open(os.path.join(here, "assets.h"), "w", newline="") as f:
    f.write("\r\n".join(out))
print("assets.h written")
